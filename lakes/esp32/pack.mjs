// Export the same geometry, line identities and timetable used by the PWA.
import fs from 'node:fs';
import path from 'node:path';
import { order, routes, project } from '../public/model.mjs';
import { makePath } from '../public/bus-layout.mjs';
const root = new URL('../public/data/', import.meta.url);
const load = (file) => JSON.parse(fs.readFileSync(new URL(file + '.json', root)));
const map = load('map'),
  rail = load('rail').lines,
  tt = load('timetable');
const out = new URL('generated/', import.meta.url);
if (!process.argv[2]) fs.mkdirSync(out, { recursive: true });
const tables = { frame: map.frame };
const q = (x) => String(x).normalize('NFKD').replace(/[\u0300-\u036f]/g, '').replace(/[–—]/g, '-').replace(/’/g, "'");
const agg = (...fields) => fields;
const literal = value => Array.isArray(value) ? '{' + value.map(literal).join(',') + '}' : JSON.stringify(value);
const rows = (name, type, data) => {
  tables[name] = data;
  return 'static constexpr ' + type + ' ' + name + '[] = {\n' + data.map(literal).join(',\n') + '\n};\n';
};
let h = '// Generated by pack.mjs\n';
h +=
  'static constexpr double west=' +
  map.frame.west +
  ', north=' +
  map.frame.north +
  ', units=' +
  map.frame.units +
  ', aspect=' +
  map.frame.aspect +
  ';\n';
h += 'static constexpr int mapW=' + map.frame.width + ', mapH=' + map.frame.height + ';\n';
h += rows(
  'routes',
  'Route',
  order.map((k) =>
    agg(q(k), q(routes[k].chip || k), parseInt(routes[k].colour.slice(1), 16), q(routes[k].icon || 'rail')),
  ),
);
const links = new Map();
function add(points, idx, closed = false) {
  const key = JSON.stringify(points);
  if (links.has(key)) {
    links.get(key).mask |= 1 << idx;
    return;
  }
  links.set(key, { points, mask: 1 << idx, closed });
}
for (const [i, key] of order.entries()) {
  if (rail[key]) {
    const r = rail[key],
      v = r.stations.find((s) => s.code === 'CKL')?.vertex;
    add(v === undefined ? r.track : r.track.slice(0, v + 1), i);
    if (v !== undefined) add(r.track.slice(v), i, true);
  } else for (const seg of map.routes[key]) add(seg, i);
}
const pos = (xy) => xy.map((v) => Math.round(v * 8));
const points = [],
  parts = [];
for (const { points: xy, mask, closed } of links.values()) {
  parts.push(agg(points.length, xy.length, mask, +closed));
  for (const p of xy) points.push(agg(...pos(p)));
}
h += rows('vertices', 'XY', points) + rows('segments', 'Segment', parts);
const towns = [
  ['Penrith', -2.757, 54.663],
  ['Keswick', -3.139, 54.601],
  ['Ambleside', -2.963, 54.431],
  ['Workington', -3.546, 54.644],
  ['Cockermouth', -3.366, 54.664],
  ['Grasmere', -3.023, 54.458],
  ['Coniston', -3.074, 54.369],
  ['Bowness', -2.922, 54.365],
  ['Dungeon Ghyll', -3.102, 54.445],
  ['Patterdale', -2.935, 54.534],
  ['Glenridding', -2.952, 54.544],
  ['Hawkshead', -3, 54.375],
  ['Pooley Bridge', -2.821, 54.612],
  ['Bassenthwaite', -3.2, 54.679],
];
const places = towns.map(([n, x, y]) => agg(q(n), agg(...pos(project([x, y], map.frame))), -1, q(''), 0));
for (const [k, r] of Object.entries(rail))
  for (const s of r.stations)
    places.push(agg(q(s.name), agg(...pos(s.point)), order.indexOf(k), q(s.code), s.vertex));
h += rows('places', 'Place', places);
const stops = Object.entries(tt.stops),
  stopIds = new Map(stops.map(([k], i) => [k, i]));
const masks = tt.groups.map(() => 0);
for (const trip of tt.trips)
  for (const [ref] of tt.patterns[trip.pattern])
    masks[tt.stops[ref].group] |= 1 << order.indexOf(trip.route);
h += rows(
  'groups',
  'Group',
  tt.groups.map((g, i) => {
    const pp = g.refs.map((k) => tt.stops[k].point);
    const center = [0, 1].map((j) => pp.reduce((a, p) => a + p[j], 0) / pp.length);
    return agg(q(g.name), q(g.town), agg(...pos(project(center, map.frame))), masks[i]);
  }),
);
h += rows(
  'stops',
  'Stop',
  stops.map(([k, s]) => agg(q(k), s.group, q(s.side))),
);
const calls = [],
  patterns = [];
for (const p of tt.patterns) {
  patterns.push(agg(calls.length, p.length));
  for (const [ref, a, d, pickup, exact] of p) calls.push(agg(stopIds.get(ref), a, d, pickup, exact));
}
h += rows('calls', 'Call', calls) + rows('patterns', 'Pattern', patterns);
const svc = Object.keys(tt.calendars);
h += 'static constexpr int firstDay=' + Math.floor(Date.parse(tt.start) / 86400000) + ';\n';
h += rows(
  'calendar',
  'char *const',
  svc.map((k) => q(tt.calendars[k])),
).replace('constexpr char *const', 'constexpr const char *const');
h += rows(
  'trips',
  'Trip',
  tt.trips.map((t) =>
    agg(order.indexOf(t.route), svc.indexOf(t.service), t.start, t.pattern, q(t.destination), t.path),
  ),
);
if (!process.argv[2]) fs.writeFileSync(new URL('network.inc', out), h);
const replay = load('replay');
tables.firstDay = Math.floor(Date.parse(tt.start) / 86400000);
tables.recordings = replay.frames.map(f => JSON.stringify(f));
if (process.argv[2]) {
  fs.writeFileSync(process.argv[2], JSON.stringify(tables));
  // Directed trip shapes use packed map coordinates and cumulative lengths for fast walks on the tablet.
  const u32 = n => { const out = Buffer.alloc(4); out.writeUInt32LE(n); return out; };
  const chunks = [u32(tt.paths.length)];
  for (const trace of tt.paths) {
    const points = makePath(trace.map(p => pos(project(p, map.frame)).map(n => n / 8)));
    if (points.length < 2) throw Error('Empty directed bus path');
    const bytes = Buffer.alloc(points.length * 8);
    points.forEach(({ x, y, distance }, i) => {
      bytes.writeInt16LE(x * 8, i * 8);
      bytes.writeInt16LE(y * 8, i * 8 + 2);
      bytes.writeFloatLE(distance, i * 8 + 4);
    });
    chunks.push(u32(points.length), bytes);
  }
  fs.writeFileSync(path.join(path.dirname(process.argv[2]), 'bus-paths.bin'), Buffer.concat(chunks));
}
else fs.writeFileSync(
  new URL('replay.inc', out),
  'static const char *const recordings[] = {\n' +
    replay.frames.map((f) => 'R"json(' + JSON.stringify(f) + ')json"').join(',\n') +
    '\n};\n',
);
